# ---- Parameters ----
APPLY_RX = False        # world-space Rx(-pi/2) to convert Y-up -> Z-up (toggle if needed)
BOX_SIZE = (0.4, 0.6, 0.25)   # (X,Y,Z) half-dimensions -> box ~ (0.8 x 0.5 x 1.2)
SAVE_MP4 = False
MP4_PATH = "box_rotation.mp4"
FPS = 20


# ---- Math helpers ----
def aa_to_R(v):
    """Axis-angle (3,) -> rotation matrix (3,3) via Rodrigues."""
    theta = np.linalg.norm(v)
    if theta < 1e-8:
        return np.eye(3)
    k = v / theta
    K = np.array([[0, -k[2], k[1]],
                  [k[2], 0, -k[0]],
                  [-k[1], k[0], 0]], dtype=np.float64)
    return np.eye(3) + np.sin(theta) * K + (1 - np.cos(theta)) * (K @ K)

def Rx(angle):
    c, s = np.cos(angle), np.sin(angle)
    return np.array([[1,0,0],[0,c,-s],[0,s,c]], dtype=np.float64)


# ---- Build a box centered at origin ----
hx, hy, hz = BOX_SIZE
# 8 vertices
verts0 = np.array([
    [-hx, -hy, -hz],
    [ hx, -hy, -hz],
    [ hx,  hy, -hz],
    [-hx,  hy, -hz],
    [-hx, -hy,  hz],
    [ hx, -hy,  hz],
    [ hx,  hy,  hz],
    [-hx,  hy,  hz],
], dtype=np.float64)

# edges as index pairs (12 edges)
edges = [
    (0,1),(1,2),(2,3),(3,0),     # bottom face
    (4,5),(5,6),(6,7),(7,4),     # top face
    (0,4),(1,5),(2,6),(3,7)      # verticals
]

# ---- Precompute per-frame rotation matrices ----
R_seq = np.stack([aa_to_R(v) for v in aa], axis=0)  # (T,3,3)
if APPLY_RX:
    R_world = Rx(-np.pi/2)                           # world-pre multiply
    R_seq = np.einsum('ij,tjk->tik', R_world, R_seq) # R_seq = Rx @ R

